static inline uint32_t example1_angle_to_compare(int angle)
{
    return (angle - SERVO_MIN_DEGREE) * (SERVO1_MAX_PULSEWIDTH_US - SERVO1_MIN_PULSEWIDTH_US) / (SERVO_MAX_DEGREE - SERVO_MIN_DEGREE) + SERVO1_MIN_PULSEWIDTH_US;
}

